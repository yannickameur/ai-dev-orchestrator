"""Realization reports — a detailed, auditable snapshot of one WorkItem's
realization (Slice 18).

Answers "what actually happened to this WorkItem, in order, and why?" —
distinct from :mod:`~orchestrator.activity_report`, which stays a
release/MVP-level consolidation. A ``RealizationReport`` is finer-grained:
one WorkItem, every pre-flight/recommendation/adaptive decision/execution/
handoff/wait/validation/review it ever went through, in chronological
order. ``ActivityReport`` may reference ``realization_report_id``s later;
this module never duplicates or replaces it.

SOURCE OF TRUTH IS NEVER THE HTML: a ``RealizationReport`` is a pure,
deterministic aggregation of already-persisted facts read from
``ProjectStateStore``/``ExecutionStore``/``HandoffStore``/
``ValidationStore``/``ReviewStore``/``WaitStore``/
``ExecutionRecommendationStore``/``AdaptiveExecutionDecisionStore`` — never
invented, never LLM-authored. ``render_html()`` is a pure, structure-to-text
projection of an already-built ``RealizationReport``; nothing in this
codebase is ever allowed to parse that HTML back into state — a future
worker may be handed the HTML (or the report) as extra *context*, but
``HandoffRecord`` remains the one canonical, machine-readable passation
artifact (see ``orchestrator.handoff``).

IMMUTABLE, INSERT-ONLY: a ``RealizationReport`` is a snapshot at
``generated_at`` — it is never updated in place. Generating again (e.g.
after a handoff, or after final completion) always produces a new
``report_id``; the previous report is kept forever, exactly like
``PlannerProposal``/``RoadmapApplication``/``ExecutionRecommendation``
before it. This is what makes an intermediate report usable as a durable
passation artifact: a caller can trust that a report it saw once will
never change under it.

DETERMINISTIC SUMMARY, NEVER AN LLM: the human-readable summary at the top
of the report (and the whole render) is built by small, explicit rules
over the aggregated facts (see ``_build_summary_text``/``_derive_status``)
— never generated by a worker.
"""


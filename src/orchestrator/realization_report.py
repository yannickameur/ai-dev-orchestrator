class RealizationReportStoreError(Exception):
    """Base for RealizationReportStore domain errors."""


class UnknownRealizationReportError(RealizationReportStoreError):
    def __init__(self, report_id: str) -> None:
        super().__init__(f"unknown realization report: {report_id!r}")
        self.report_id = report_id


class DuplicateRealizationReportError(RealizationReportStoreError):
    def __init__(self, report_id: str) -> None:
        super().__init__(f"realization report already exists: {report_id!r}")
        self.report_id = report_id


class CorruptRealizationReportError(RealizationReportStoreError):
    def __init__(self, report_id: str, detail: str) -> None:
        super().__init__(f"corrupt realization report {report_id!r}: {detail}")
        self.report_id = report_id



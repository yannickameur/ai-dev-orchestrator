class RealizationReportStore:
    """Synchronous, sqlite3-backed, insert-only store for RealizationReports."""

    def __init__(self, db_path: str | Path, *, clock: Clock | None = None) -> None:
        self._clock = clock or (lambda: datetime.now(timezone.utc))
        self._conn = sqlite3.connect(str(db_path))
        self._conn.row_factory = sqlite3.Row
        with self._conn:
            self._conn.execute(_CREATE_TABLE_SQL)

    def close(self) -> None:
        self._conn.close()

    def record(self, report: RealizationReport) -> RealizationReport:
        """Inserts a new report — never updated, never deleted. A second
        generation for the same WorkItem always uses a new report_id."""
        try:
            with self._conn:
                self._conn.execute(
                    "INSERT INTO realization_reports (report_id, project_id, mvp_id, work_item_id, "
                    "generated_at, report_status, final_work_item_status, payload) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                    (
                        report.report_id, report.project_id, report.mvp_id, report.work_item_id,
                        report.generated_at.isoformat(), report.report_status.value,
                        report.final_work_item_status, _serialize(report),
                    ),
                )
        except sqlite3.IntegrityError as exc:
            raise DuplicateRealizationReportError(report.report_id) from exc
        return report

    def get(self, report_id: str) -> RealizationReport:
        row = self._conn.execute(
            "SELECT * FROM realization_reports WHERE report_id = ?", (report_id,)
        ).fetchone()
        if row is None:
            raise UnknownRealizationReportError(report_id)
        try:
            return _deserialize(row["payload"])
        except (ValueError, TypeError, KeyError, json.JSONDecodeError) as exc:
            raise CorruptRealizationReportError(report_id, str(exc)) from exc

    def list_for_work_item(self, work_item_id: str) -> list[RealizationReport]:
        """Every report ever generated for a WorkItem, oldest first — none ever overwritten."""
        rows = self._conn.execute(
            "SELECT report_id FROM realization_reports WHERE work_item_id = ? ORDER BY generated_at ASC",
            (work_item_id,),
        ).fetchall()
        return [self.get(row["report_id"]) for row in rows]

    def latest_for_work_item(self, work_item_id: str) -> RealizationReport | None:
        reports = self.list_for_work_item(work_item_id)
        return reports[-1] if reports else None



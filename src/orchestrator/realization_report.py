_INCIDENT_STATUSES = {ExecutionStatus.INTERRUPTED, ExecutionStatus.RECOVERY_REQUIRED}


def _derive_status(work_item_status: WorkItemStatus, *, has_handoffs: bool) -> RealizationReportStatus:
    if work_item_status is WorkItemStatus.COMPLETED:
        return RealizationReportStatus.COMPLETED
    if work_item_status is WorkItemStatus.FAILED:
        return RealizationReportStatus.FAILED
    if work_item_status is WorkItemStatus.BLOCKED:
        return RealizationReportStatus.BLOCKED
    if has_handoffs:
        return RealizationReportStatus.HANDOFF_READY
    return RealizationReportStatus.IN_PROGRESS


def _build_summary_text(
    *, work_item: WorkItem, report_status: RealizationReportStatus, executions: tuple[ExecutionEntry, ...],
    waits: tuple[WaitEntry, ...], incidents: tuple[str, ...],
) -> str:
    workers = sorted({e.worker_id for e in executions})
    sentences = [
        f"WorkItem {work_item.work_item_id!r} ({work_item.title}) was worked on by "
        f"{len(workers)} worker(s) across {len(executions)} execution(s)."
    ]
    if incidents:
        sentences.append(
            f"{len(incidents)} incident(s) were recorded during realization "
            "(see the Incidents section for details)."
        )
    if waits:
        sentences.append(f"{len(waits)} quota wait(s) occurred before completion.")
    if len(workers) > 1:
        sentences.append(f"Work was handed off across workers: {', '.join(workers)}.")
    sentences.append(f"Current report status: {report_status.value}.")
    return " ".join(sentences)


class RealizationReportService:
    """Builds a ``RealizationReport`` by aggregating already-persisted facts.

    Every store beyond the three required ones is optional, mirroring the
    opt-in composition already used throughout ``MVPManager`` — a project
    that never configured reviews/waits/adaptive execution simply gets an
    empty section for that part of the report, never an error.
    """

    def __init__(
        self,
        project_state_store: ProjectStateStore,
        execution_store: ExecutionStore,
        handoff_store: HandoffStore,
        report_store: RealizationReportStore,
        *,
        validation_store=None,
        review_store=None,
        wait_store=None,
        recommendation_store=None,
        decision_store=None,
        git_work_item_store=None,
        qa_run_store=None,
        clock: Clock | None = None,
        id_factory: IdFactory | None = None,
    ) -> None:
        self._project_state_store = project_state_store
        self._execution_store = execution_store
        self._handoff_store = handoff_store
        self._report_store = report_store
        self._validation_store = validation_store
        self._review_store = review_store
        self._wait_store = wait_store
        self._recommendation_store = recommendation_store
        self._decision_store = decision_store
        self._git_work_item_store = git_work_item_store
        self._qa_run_store = qa_run_store
        self._clock = clock or (lambda: datetime.now(timezone.utc))
        self._id_factory = id_factory or _default_id_factory

    def generate(self, *, project_id: str, mvp_id: str, work_item_id: str) -> RealizationReport:
        work_item = self._project_state_store.get_work_item(work_item_id)

        executions = tuple(
            _to_execution_entry(e) for e in self._execution_store.list_for_task(work_item_id)
        )
        handoffs = tuple(
            _to_handoff_entry(h) for h in self._handoff_store.list_for_work_item(work_item_id)
        )
        validations = (
            tuple(_to_validation_entry(v) for v in self._validation_store.list_results_for_work_item(work_item_id))
            if self._validation_store is not None else ()
        )
        reviews = (
            tuple(_to_review_entry(r) for r in self._review_store.list_for_work_item(work_item_id))
            if self._review_store is not None else ()
        )
        waits = (
            tuple(
                _to_wait_entry(w) for w in self._wait_store.list_for_mvp(mvp_id)
                if w.work_item_id == work_item_id
            )
            if self._wait_store is not None else ()
        )
        recommendations = (
            tuple(_to_recommendation_entry(r) for r in self._recommendation_store.list_for_work_item(work_item_id))
            if self._recommendation_store is not None else ()
        )
        decisions = (
            tuple(_to_decision_entry(d) for d in self._decision_store.list_for_work_item(work_item_id))
            if self._decision_store is not None else ()
        )

        git_work_item = (
            self._git_work_item_store.try_get(work_item_id)
            if self._git_work_item_store is not None else None
        )
        git_events = (
            tuple(self._git_work_item_store.list_events(work_item_id))
            if self._git_work_item_store is not None and git_work_item is not None else ()
        )

        qa_run = (
            self._qa_run_store.latest_for_work_item(work_item_id)
            if self._qa_run_store is not None else None
        )
        qa_result = (
            self._qa_run_store.get_result(qa_run.run_id)
            if self._qa_run_store is not None and qa_run is not None else None
        )
        qa_events = (
            tuple(self._qa_run_store.list_events(qa_run.run_id))
            if self._qa_run_store is not None and qa_run is not None else ()
        )

        incidents = _collect_incidents(
            work_item=work_item, executions=executions, validations=validations, reviews=reviews,
        )
        timeline = _build_timeline(
            executions=executions, recommendations=recommendations, decisions=decisions,
            handoffs=handoffs, validations=validations, reviews=reviews, waits=waits,
            git_events=git_events, qa_events=qa_events,
        )

        git_sha_initial = executions[0].git_sha_before if executions else None
        git_sha_after_values = [e.git_sha_after for e in executions if e.git_sha_after]
        git_sha_final = git_sha_after_values[-1] if git_sha_after_values else None

        report_status = _derive_status(work_item.status, has_handoffs=bool(handoffs))
        summary_text = _build_summary_text(
            work_item=work_item, report_status=report_status, executions=executions, waits=waits, incidents=incidents,
        )

        report = RealizationReport(
            report_id=self._id_factory(), project_id=project_id, mvp_id=mvp_id, work_item_id=work_item_id,
            generated_at=self._clock(), report_status=report_status, final_work_item_status=work_item.status.value,
            objective=work_item.title, summary_text=summary_text,
            acceptance_criteria=work_item.acceptance_criteria, dependencies=tuple(sorted(work_item.dependencies)),
            git_sha_initial=git_sha_initial, git_sha_final=git_sha_final,
            git_base_branch=git_work_item.base_branch if git_work_item is not None else None,
            git_work_branch=git_work_item.work_branch if git_work_item is not None else None,
            git_merge_status=git_work_item.status.value if git_work_item is not None else None,
            git_merged_sha=git_work_item.merged_sha if git_work_item is not None else None,
            git_pull_request_number=git_work_item.pull_request_number if git_work_item is not None else None,
            git_pull_request_url=git_work_item.pull_request_url if git_work_item is not None else None,
            qa_run_id=qa_run.run_id if qa_run is not None else None,
            qa_engine_id=qa_run.engine_id if qa_run is not None else None,
            qa_phase=qa_run.phase.value if qa_run is not None else None,
            qa_verdict_status=qa_run.verdict.status.value if qa_run is not None and qa_run.verdict is not None else None,
            qa_expected_head_sha=qa_run.expected_head_sha if qa_run is not None else None,
            qa_observed_head_sha=qa_result.observed_head_sha if qa_result is not None else None,
            qa_tests_executed_count=len(qa_result.tests_executed) if qa_result is not None else None,
            qa_passed_count=qa_result.passed_count if qa_result is not None else None,
            qa_failed_count=qa_result.failed_count if qa_result is not None else None,
            qa_regressions=qa_result.regressions if qa_result is not None else (),
            executions=executions, recommendations=recommendations, decisions=decisions, handoffs=handoffs,
            validations=validations, reviews=reviews, waits=waits, incidents=incidents, timeline=timeline,
        )
        return self._report_store.record(report)


def _to_execution_entry(e: ExecutionRecord) -> ExecutionEntry:
    return ExecutionEntry(
        execution_id=e.execution_id, role=e.role, worker_id=e.worker_id, provider=e.provider, backend=e.backend,
        model=e.model, reasoning_effort=e.reasoning_effort, started_at=e.started_at, finished_at=e.finished_at,
        status=e.status.value, exit_code=e.exit_code, provider_session_id=e.provider_session_id,
        ralph_loop_id=e.ralph_loop_id, git_sha_before=e.git_sha_before, git_sha_after=e.git_sha_after,
    )


def _to_handoff_entry(h: HandoffRecord) -> HandoffEntry:
    return HandoffEntry(
        handoff_id=h.handoff_id, created_at=h.created_at, execution_id=h.execution_id, worker_id=h.worker_id,
        completed_work=h.completed_work, decisions=h.decisions, files_touched=h.files_touched,
        tests_run=h.tests_run, test_results=h.test_results, open_issues=h.open_issues, risks=h.risks,
        next_action=h.next_action, git_sha_after=h.git_sha_after,
    )


def _to_validation_entry(v) -> ValidationEntry:
    return ValidationEntry(
        validation_run_id=v.validation_run_id, validation_id=v.validation_id, kind=v.kind.value,
        required=v.required, status=v.status.value, started_at=v.started_at, duration_ms=v.duration_ms,
        exit_code=v.exit_code, git_sha=v.git_sha,
    )


def _to_review_entry(r) -> ReviewEntry:
    return ReviewEntry(
        review_id=r.review_id, author_worker_id=r.author_worker_id, status=r.status.value,
        started_at=r.started_at, finished_at=r.finished_at, reviewer_worker_id=r.reviewer_worker_id,
        findings_summary=tuple(f"[{f.severity}] {f.summary}" for f in r.findings),
    )


def _to_wait_entry(w) -> WaitEntry:
    return WaitEntry(
        wait_id=w.wait_id, phase=w.phase.value, reason=w.reason.value, created_at=w.created_at,
        eligible_at=w.eligible_at, status=w.status.value, resolved_at=w.resolved_at, resolution=w.resolution,
    )


def _to_recommendation_entry(r) -> RecommendationEntry:
    return RecommendationEntry(
        recommendation_id=r.recommendation_id, role=r.role, estimator_worker_id=r.estimator_worker_id,
        estimator_execution_id=r.estimator_execution_id, estimator_profile_id=r.estimator_profile_id,
        task_fingerprint=r.task_fingerprint, minimum_quality_tier=r.minimum_quality_tier.name,
        recommended_reasoning=r.recommended_reasoning, reasons=r.reasons, created_at=r.created_at,
    )


def _to_decision_entry(d) -> DecisionEntry:
    return DecisionEntry(
        decision_id=d.decision_id, recommendation_id=d.recommendation_id, role=d.role, worker_id=d.worker_id,
        provider=d.provider, backend=d.backend, profile_id=d.profile_id, quality_tier=d.quality_tier.name,
        model=d.model, reasoning_effort=d.reasoning_effort, rationale=d.rationale, created_at=d.created_at,
    )


def _collect_incidents(
    *, work_item: WorkItem, executions: tuple[ExecutionEntry, ...], validations: tuple[ValidationEntry, ...],
    reviews: tuple[ReviewEntry, ...],
) -> tuple[str, ...]:
    incidents: list[str] = []
    for e in executions:
        if e.status in (ExecutionStatus.INTERRUPTED.value, ExecutionStatus.RECOVERY_REQUIRED.value):
            incidents.append(f"execution {e.execution_id} ended as {e.status}")
    for v in validations:
        if v.required and v.status not in ("passed", "skipped"):
            incidents.append(f"required validation {v.validation_id} ended as {v.status}")
    for r in reviews:
        if r.status == "rejected":
            incidents.append(f"review {r.review_id} rejected the work")
    if work_item.status is WorkItemStatus.BLOCKED and work_item.blocked_reason:
        incidents.append(f"work item blocked: {work_item.blocked_reason}")
    return tuple(incidents)


def _build_timeline(
    *, executions: tuple[ExecutionEntry, ...], recommendations: tuple[RecommendationEntry, ...],
    decisions: tuple[DecisionEntry, ...], handoffs: tuple[HandoffEntry, ...],
    validations: tuple[ValidationEntry, ...], reviews: tuple[ReviewEntry, ...], waits: tuple[WaitEntry, ...],
    git_events: tuple[tuple[str, str, datetime], ...] = (),
    qa_events: tuple[tuple[str, str, datetime], ...] = (),
) -> tuple[TimelineEntry, ...]:
    entries: list[TimelineEntry] = []

    for r in recommendations:
        entries.append(TimelineEntry(
            timestamp=r.created_at, entry_type=TIMELINE_RECOMMENDATION,
            summary=f"Pre-flight recommendation for role={r.role!r}: minimum_quality_tier={r.minimum_quality_tier}",
            references=(f"recommendation_id={r.recommendation_id}", f"estimator_worker_id={r.estimator_worker_id}"),
        ))
    for d in decisions:
        entries.append(TimelineEntry(
            timestamp=d.created_at, entry_type=TIMELINE_ADAPTIVE_DECISION,
            summary=f"Adaptive decision: worker={d.worker_id} profile={d.profile_id} tier={d.quality_tier}",
            references=(f"decision_id={d.decision_id}", f"recommendation_id={d.recommendation_id}"),
        ))
    for e in executions:
        entries.append(TimelineEntry(
            timestamp=e.started_at, entry_type=TIMELINE_EXECUTION_STARTED,
            summary=f"Execution started: role={e.role} worker={e.worker_id} model={e.model}",
            references=(f"execution_id={e.execution_id}",),
        ))
        if e.finished_at is not None:
            entries.append(TimelineEntry(
                timestamp=e.finished_at, entry_type=TIMELINE_EXECUTION_FINISHED,
                summary=f"Execution finished: status={e.status}",
                references=(f"execution_id={e.execution_id}",),
            ))
    for w in waits:
        entries.append(TimelineEntry(
            timestamp=w.created_at, entry_type=TIMELINE_WAIT_STARTED,
            summary=f"Wait started: phase={w.phase} reason={w.reason} eligible_at={w.eligible_at.isoformat()}",
            references=(f"wait_id={w.wait_id}",),
        ))
        if w.resolved_at is not None:
            entries.append(TimelineEntry(
                timestamp=w.resolved_at, entry_type=TIMELINE_WAIT_RESOLVED,
                summary=f"Wait resolved: {w.resolution}",
                references=(f"wait_id={w.wait_id}",),
            ))
    for h in handoffs:
        entries.append(TimelineEntry(
            timestamp=h.created_at, entry_type=TIMELINE_HANDOFF,
            summary=f"Handoff created: next_action={h.next_action or '(none)'}",
            references=(f"handoff_id={h.handoff_id}",),
        ))
    for v in validations:
        entries.append(TimelineEntry(
            timestamp=v.started_at, entry_type=TIMELINE_VALIDATION,
            summary=f"Quality gate {v.validation_id} ({v.kind}): {v.status}",
            references=(f"validation_run_id={v.validation_run_id}",),
        ))
    for r in reviews:
        entries.append(TimelineEntry(
            timestamp=r.started_at, entry_type=TIMELINE_REVIEW_STARTED,
            summary=f"Review started by author={r.author_worker_id}",
            references=(f"review_id={r.review_id}",),
        ))
        entries.append(TimelineEntry(
            timestamp=r.finished_at, entry_type=TIMELINE_REVIEW_FINISHED,
            summary=f"Review verdict: {r.status}",
            references=(f"review_id={r.review_id}",),
        ))
    for event_type, detail, created_at in git_events:
        entries.append(TimelineEntry(
            timestamp=created_at, entry_type=event_type,
            summary=f"Git governance: {event_type} — {detail}",
            references=(),
        ))
    for event_type, detail, created_at in qa_events:
        entries.append(TimelineEntry(
            timestamp=created_at, entry_type=f"qa_{event_type}",
            summary=f"QA: {event_type} — {detail}",
            references=(),
        ))

    # Deterministic ordering: chronological, ties broken by a stable,
    # fully-specified key so two reports built from identical facts always
    # render an identical timeline.
    entries.sort(key=lambda t: (t.timestamp, t.entry_type, t.summary, t.references))
    return tuple(entries)



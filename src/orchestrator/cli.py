_SHORT_DESCRIPTION = (
    "Operate an AI Dev Orchestrator-governed project from an aido.yaml — "
    "no custom Python harness required. See docs/PROJECT_CONFIG.md for "
    "the config schema."
)


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="aido", description=_SHORT_DESCRIPTION)
    subparsers = parser.add_subparsers(dest="command", required=True)

    init_parser = subparsers.add_parser("init", help="Create a project, or write a starting aido.yaml template.")
    init_parser.add_argument("config", nargs="?", default=DEFAULT_CONFIG_PATH,
                             metavar="config-or-parent", help="Legacy config path, or new project's parent.")
    init_parser.add_argument("new_project", nargs="?", metavar="project-name",
                             help="Create a complete project under the parent path.")
    init_parser.add_argument("--workers-registry", default=None)
    init_parser.add_argument("--project-id", default=None)
    init_parser.add_argument("--project-name", default=None)
    init_parser.add_argument("--workspace", default=None)
    init_parser.add_argument(
        "--permission-mode", choices=[m.value for m in ExecutionPermissionMode], default=None,
    )
    init_parser.set_defaults(func=_cmd_init)

    validate_parser = subparsers.add_parser("validate", help="Load/validate a config, print facts.")
    validate_parser.add_argument("config", nargs="?", default=DEFAULT_CONFIG_PATH)
    validate_parser.set_defaults(func=_cmd_validate)

    run_parser = subparsers.add_parser(
        "run", help="Bootstrap (idempotent) and drive WorkItem Flow. Also the resume operation.",
    )
    run_parser.add_argument("config", nargs="?", default=DEFAULT_CONFIG_PATH)
    run_parser.add_argument("--max-cycles", type=int, default=DEFAULT_MAX_CYCLES)
    run_parser.set_defaults(func=_cmd_run)

    status_parser = subparsers.add_parser("status", help="Read persisted state — no provider calls.")
    status_parser.add_argument("config", nargs="?", default=DEFAULT_CONFIG_PATH)
    status_parser.add_argument(
        "--probe", action="store_true",
        help="Also perform one real, explicit provider probe (network/CLI). Omit for zero provider calls.",
    )
    status_parser.set_defaults(func=_cmd_status)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())

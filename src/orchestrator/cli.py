_INIT_GITIGNORE = "/.ralph/\n.env\n.env.*\n"


def _print_git_recovery(workspace: Path) -> None:
    print(f'\nFrom {workspace} run:\n\n  cd {shlex.quote(str(workspace))}\n'
          '  git init -b main\n  git add .\n'
          '  git commit -m "Initialize AIDO project"\n')


def _initialize_project_git(workspace: Path) -> bool:
    git = shutil.which("git")
    if git is None:
        print("WARNING: Git is not installed or is not available in PATH.")
        print("\nAIDO requires a Git repository before governed development can start.")
        print("After installing Git:")
        _print_git_recovery(workspace)
        return False
    for command in (["init", "-b", "main"], ["add", "."],
                    ["commit", "-m", "Initialize AIDO project"]):
        try:
            subprocess.run([git, *command], cwd=workspace, check=True,
                           capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.SubprocessError) as exc:
            print(f"aido init: Git step '{command[0]}' failed. Scaffold preserved.", file=sys.stderr)
            detail = str(getattr(exc, "stderr", "") or exc)
            print(detail, file=sys.stderr)
            if any(marker in detail.lower() for marker in
                   ("identity", "user.email", "user.name", "auto-detect email", "who you are")):
                print("Configure your Git identity before retrying the commit.", file=sys.stderr)
            _print_git_recovery(workspace)
            return False
    return True


def _cmd_init(args: argparse.Namespace) -> int:
    try:
        if args.new_project is None:
            return _write_init_config(args)
        return _scaffold_project(args)
    except (OSError, ValueError) as exc:
        print(f"aido init: {exc}", file=sys.stderr)
        return 1


def _scaffold_project(args: argparse.Namespace) -> int:
    name = args.new_project
    # One portable directory component, never a path, option or control text.
    if not re.fullmatch(r"[^\W_][\w .-]*", name) or name.endswith((".", " ")):
        print("aido init: project-name must be a single directory name, not a path. "
              "No file was modified.", file=sys.stderr)
        return 1
    if args.workspace is not None or args.project_name is not None:
        print("aido init: --workspace and --project-name belong to the legacy config mode; "
              "the two positional arguments define the new project. No file was modified.",
              file=sys.stderr)
        return 1
    parent = Path(args.config).expanduser().resolve()
    target = parent / name
    if target.is_symlink():
        print(f"aido init: {target} is a symlink. No file was modified.", file=sys.stderr)
        return 1
    if target.exists() and (not target.is_dir() or any(target.iterdir())):
        print(f"aido init: {target} already exists and is not empty.\nNo file was modified.",
              file=sys.stderr)
        return 1
    target.mkdir(parents=True, exist_ok=True)
    config_args = argparse.Namespace(**vars(args))
    config_args.config = str(target / "aido.yaml")
    config_args.workspace = str(target)
    config_args.project_name = name
    if _write_init_config(config_args) != 0:
        return 1
    for filename, content in (("README.md", _README_TEMPLATE.format(name=name)),
                              ("ROADMAP.md", _ROADMAP_TEMPLATE.format(name=name)),
                              (".gitignore", _INIT_GITIGNORE)):
        (target / filename).write_text(content, encoding="utf-8")
    git_ready = _initialize_project_git(target)
    print("\nAIDO — project initialized" if git_ready else "\nAIDO — scaffold created; Git setup incomplete")
    print(f"\nProject: {name}\nDirectory: {target}")
    if git_ready:
        print("Git: initialized on branch main\nInitial commit: created")
    print("\nFiles created:\n  README.md\n  ROADMAP.md\n  aido.yaml\n  .gitignore")
    print(f"""
Next steps:

1. cd {shlex.quote(str(target))}

2. Edit README.md
   Describe what the project is, its purpose and its main constraints.

3. Edit ROADMAP.md
   Define the first milestone, objective and expected outcomes.

4. Edit aido.yaml
   Define the first executable MVP:
   - objective
   - acceptance criteria
   - work items
   - QA commands

5. Validate (after completing Git setup if needed):
   aido validate

6. Commit your project definition:
   git add README.md ROADMAP.md aido.yaml
   git commit -m "Define initial project"

7. Start governed development:
   aido run

No development has been started.
""")
    return 0 if git_ready else 1


def _relpath(target: Path, base: Path) -> str:
    import os

    return os.path.relpath(target, base)


# --- aido validate -------------------------------------------------------

def _cmd_validate(args: argparse.Namespace) -> int:
    config = _load_config(args.config)
    if config is None:
        return 1

    registry = config.load_worker_registry()
    enabled = registry.enabled_workers()
    providers = sorted({w.provider for w in enabled})

    print(f"project: {config.project.id} ({config.project.name})")
    print(f"workspace: {config.project.workspace}")
    print(f"state_dir: {config.project.state_dir}")
    print(f"mvp: {config.mvp.id}")
    print(f"work_items: {len(config.work_items)}")
    print(f"qa_commands: {len(config.qa_commands)}")
    print(f"enabled_workers: {len(enabled)}")
    print(f"providers: {', '.join(providers) if providers else '(none)'}")
    print(f"permission_mode: {config.execution.permission_mode.value.upper()}")
    print(f"base_branch: {config.git.base_branch}")
    print("aido validate: OK")
    return 0


# --- aido status -----------------------------------------------------------

def _cmd_status(args: argparse.Namespace) -> int:
    """STRICTLY READ-ONLY *unless* ``--probe`` is explicitly given: never
    creates ``state_dir`` or any store file, never runs ``CREATE TABLE``/a
    migration, never writes a row — see ``OrchestratorEngine.status()``.
    Never uses the write-capable ``ProjectRuntime.open()`` composition (no
    QuotaManager/ProviderAdapter/WorkerSelector/RalphExecutionEngine/
    InternalQAEngine/GitGovernanceService are ever instantiated unless
    ``--probe`` is set, and even then only ``OrchestratorEngine.
    probe_workers()``'s own, already-tested QuotaManager/ProviderAdapter
    composition — never a second one built here). One ``OrchestratorEngine``
    is built and reused for both ``.status()`` and (if requested)
    ``.probe_workers()`` — never a second, independent traversal of
    persisted state built directly in this module (REUSE FIRST, AUD-4)."""
    config = _load_config(args.config)
    if config is None:
        return 1

    try:
        registry = config.load_worker_registry()
    except WorkerRegistryError as exc:
        print(f"aido: invalid worker registry — {exc}", file=sys.stderr)
        return 1

    engine = OrchestratorEngine(config, provider_adapters=getattr(args, "provider_adapters", None))
    _print_project_status(engine)

    probes: tuple[Any, ...] | None = None
    if getattr(args, "probe", False):
        try:
            probes = engine.probe_workers()
        except EngineConfigError as exc:
            print(f"aido status --probe: FAIL — {exc}", file=sys.stderr)
            return 1

    print()
    _print_workers_section(registry, probes)

    if probes is not None:
        print()
        _print_provider_quotas_section(probes)

    return 0


def _print_project_status(engine: OrchestratorEngine) -> None:
    """Pure rendering over ``OrchestratorEngine.status()``'s own
    ``ProjectStatusSnapshot`` — the exact same real, read-only status path
    exposed to any other frontend (P13, e.g. AIDO Code), never a second,
    independent traversal of ``ProjectStatusReader`` built here (REUSE
    FIRST, AUD-4). A genuine read failure (corrupted state, I/O error, ...)
    propagates rather than being folded into ``NOT_INITIALIZED`` (AUD-3):
    only ``OrchestratorEngine.status()``'s own explicit, typed
    "project truly never bootstrapped" case renders that message."""
    snapshot = engine.status()
    if not snapshot.initialized:
        print("NOT_INITIALIZED")
        print("Run `aido run` to initialize and start this project.")
        return

    print(f"project: {snapshot.project_id} ({snapshot.project_name})")
    mvp = snapshot.mvp
    if mvp is None or mvp.status is None:
        print(f"mvp: {mvp.mvp_id if mvp is not None else '?'} (not yet created)")
    else:
        print(f"mvp: {mvp.mvp_id} status={mvp.status}")

    counts = {status: 0 for status in WorkItemStatus}
    for wi in snapshot.work_items:
        counts[WorkItemStatus(wi.status)] += 1
        line = f"  {wi.work_item_id}: {wi.status}"
        if wi.blocked_reason:
            line += f" (blocked_reason={wi.blocked_reason})"
        print(line)

        if wi.last_execution is not None:
            last = wi.last_execution
            worker_label = (
                f"{last.worker_display_name} [{last.worker_id}]"
                if last.worker_display_name else f"{last.worker_id} [unknown display name]"
            )
            print(
                f"      last execution: worker={worker_label} provider={last.provider} "
                f"status={last.status} "
                f"permission_mode={last.permission_mode or 'unknown'}"
            )
        if wi.wait is not None:
            print(
                f"      wait: phase={wi.wait.phase} "
                f"eligible_at={wi.wait.eligible_at} "
                f"providers={','.join(wi.wait.providers) or '(any)'}"
            )

    print("\nWorkItem status counts:")
    for status in _REPORTED_STATUSES:
        print(f"  {status.value}: {counts[status]}")


def _print_workers_section(registry: "WorkerRegistry", probes: "tuple[Any, ...] | None") -> None:
    """Shared by ``aido status``/``aido status --probe``: one rendering
    path for the worker list, never duplicated between the two modes.
    ``probes`` is ``None`` for the no-probe case (no ``probe=`` line at
    all); otherwise each worker's line gets the observable state of ITS
    OWN provider (never a fabricated per-worker state — two workers on
    the same provider show the exact same probe result, see ROADMAP.md)."""
    by_provider = {p.provider: p for p in (probes or ())}
    print("Workers:")
    for worker in registry.all_workers():
        state = "enabled" if worker.enabled else "disabled"
        line = (
            f"  {worker.worker_id} — {worker.display_name}\n"
            f"    {state}\n"
            f"    provider={worker.provider}\n"
            f"    backend={worker.backend}\n"
            f"    model={worker.profile().model}"
        )
        print(line)
        if probes is not None:
            if not worker.enabled:
                # A disabled worker's provider is never probed at all
                # (probe_workers() only probes enabled workers' providers)
                # — "disabled" is the honest fact here, never a fabricated
                # "unknown" that implies a probe was attempted.
                probe_state = "disabled"
            else:
                snapshot = by_provider.get(worker.provider)
                probe_state = snapshot.reason if snapshot is not None else "unknown"
            print(f"    probe={probe_state}")


def _print_provider_quotas_section(probes: "tuple[Any, ...]") -> None:
    """Quota is a PROVIDER-level fact, never per-worker (ROADMAP.md): one
    block per distinct provider actually probed, regardless of how many
    workers share it."""
    print("Provider quotas:")
    for snapshot in sorted(probes, key=lambda p: p.provider):
        print(f"  {snapshot.provider}:")
        if not snapshot.quota_windows:
            print("    quota: unknown")
        for window in snapshot.quota_windows:
            used = f"{window.utilization:.0%}" if window.utilization is not None else "unknown"
            remaining = f"{window.remaining:.0%}" if window.remaining is not None else "unknown"
            reset = window.reset_at or "unknown"
            print(f"    {window.window_type}:")
            print(f"      used: {used}")
            print(f"      remaining: {remaining}")
            print(f"      reset: {reset}")
        if snapshot.reset_credits:
            print("    reset credits:")
            for credit in snapshot.reset_credits:
                count = credit.available_count if credit.available_count is not None else "unknown"
                print(f"      {credit.title}: {credit.status} (available: {count})")


# --- aido run --------------------------------------------------------------

def _cmd_run(args: argparse.Namespace) -> int:
    config = _load_config(args.config)
    if config is None:
        return 1

    if config.execution.permission_mode is ExecutionPermissionMode.UNRESTRICTED:
        print("WARNING: project requests UNRESTRICTED worker execution permissions.")

    try:
        runtime = ProjectRuntime.open(
            config,
            clock=getattr(args, "clock", None),
            provider_adapters=getattr(args, "provider_adapters", None),
            subprocess_runner=getattr(args, "subprocess_runner", None),
        )
    except ProjectRuntimeError as exc:
        print(f"aido run: FAIL — {exc}", file=sys.stderr)
        return 1

    try:
        try:
            runtime.bootstrap()
        except ConfigRuntimeConflictError as exc:
            print(f"aido run: FAIL — {exc}", file=sys.stderr)
            return 1

        cycles_run = 0
        for cycle in range(1, args.max_cycles + 1):
            cycles_run = cycle
            result = asyncio.run(runtime.manager.run_next_work_item(config.mvp.id))
            if result is None:
                print("aido run: nothing currently eligible/due.")
                break

            line = f"{result.work_item.work_item_id} -> {result.work_item.status.value}"
            if result.work_item.blocked_reason:
                line += f" ({result.work_item.blocked_reason})"
            print(line)
            if result.work_item.status is WorkItemStatus.WAITING and result.wait is not None:
                print(
                    f"  WAITING: phase={result.wait.phase.value} "
                    f"eligible_at={result.wait.eligible_at} "
                    f"providers={','.join(result.wait.providers) or '(any)'}"
                )

            all_terminal = all(
                wi.status in _TERMINAL_STATUSES
                for wi in runtime.project_store.list_work_items(config.mvp.id)
            )
            if all_terminal:
                break
        else:
            print(f"aido run: reached --max-cycles={args.max_cycles} — re-run `aido run` to continue.")

        final_items = sorted(
            runtime.project_store.list_work_items(config.mvp.id), key=lambda w: w.work_item_id
        )
        print("\n=== summary ===")
        for wi in final_items:
            print(f"  {wi.work_item_id}: {wi.status.value}")
        all_terminal = all(wi.status in _TERMINAL_STATUSES for wi in final_items)
        print(f"cycles_run={cycles_run} all_terminal={all_terminal}")
        print(
            "Re-running `aido run` against the same config resumes this project "
            "from its persisted state — there is no separate resume command."
        )
        return 0
    finally:
        runtime.close()



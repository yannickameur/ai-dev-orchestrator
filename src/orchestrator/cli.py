_TERMINAL_STATUSES = frozenset(
    {WorkItemStatus.COMPLETED, WorkItemStatus.FAILED, WorkItemStatus.BLOCKED}
)
# Reported status counts — REVIEWING is legacy decode-only (see
# WorkItemStatus's own docstring), never a current WorkItem Flow phase,
# so it is deliberately excluded from this user-facing summary.
_REPORTED_STATUSES = tuple(s for s in WorkItemStatus if s is not WorkItemStatus.REVIEWING)


def _yaml_str(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _sanitize_id(name: str) -> str:
    slug = re.sub(r"[^a-z0-9-]+", "-", name.lower()).strip("-")
    return slug or "project"


def _load_config(path: str) -> ProjectConfig | None:
    """Loads a config, printing one clean line (never a traceback) for an
    ordinary bad config/worker-registry problem."""
    try:
        return ProjectConfig.load(path)
    except MissingGitWorkspaceError as exc:
        print("aido: this project is not initialized as a Git repository.", file=sys.stderr)
        _print_git_recovery(exc.workspace)
        print(f"Then retry:\n  aido validate {shlex.quote(str(Path(path).resolve()))}")
        return None
    except (ProjectConfigError, WorkerRegistryError) as exc:
        print(f"aido: invalid project configuration — {exc}", file=sys.stderr)
        return None


